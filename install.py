def builder_source():
    """The downloader: build_bundle.py next to this file, else the copy embedded in install.py."""
    sibling = HERE / "build_bundle.py"
    if sibling.is_file():
        return sibling.read_bytes(), str(sibling)
    if EMBEDDED_BUILDER:
        try:
            data = zlib.decompress(base64.b64decode("".join(EMBEDDED_BUILDER)))
        except (ValueError, zlib.error):
            data = b""
        if hashlib.sha256(data).hexdigest() != EMBEDDED_BUILDER_SHA256:
            die("the downloader embedded in install.py is damaged")
        return data, "built into install.py"
    die("this install.py has no built-in downloader; put build_bundle.py next to it, or use an install.py "
        "from 'build_bundle.py --parts installer'")


