def ask(prompt, default=None, check=None, optional=False):
    while True:
        shown = f" [{default}]" if default not in (None, "") else ""
        raw = input(f"  {prompt}{shown}: ").strip()
        value = raw if raw else ("" if default is None else str(default))
        if not value:
            if optional:
                log(f"answer: {prompt} = (empty)")
                return ""
            print("    a value is required")
            continue
        problem = check(value) if check else None
        if problem:
            print(f"    {problem}")
            continue
        log(f"answer: {prompt} = {value}")
        return value


def ask_yes(prompt, default=True):
    hint = "Y/n" if default else "y/N"
    while True:
        raw = input(f"  {prompt} [{hint}]: ").strip().lower()
        if not raw:
            answer = default
        elif raw in ("y", "yes"):
            answer = True
        elif raw in ("n", "no"):
            answer = False
        else:
            continue
        log(f"answer: {prompt} = {answer}")
        return answer


def ask_choice(prompt, options, default):
    """options: list of (value, label)."""
    values = [value for value, _ in options]
    if default not in values:
        default = values[0]
    print(f"  {prompt}")
    for index, (value, label) in enumerate(options, 1):
        print(f"    {index}) {label}" + ("   <- default" if value == default else ""))
    while True:
        raw = input(f"  choose 1-{len(options)} [{values.index(default) + 1}]: ").strip()
        if not raw:
            choice = default
        elif raw.isdigit() and 1 <= int(raw) <= len(options):
            choice = values[int(raw) - 1]
        else:
            continue
        log(f"answer: {prompt} = {choice}")
        return choice


def ask_secret(prompt, check=None, confirm=False):
    while True:
        value = getpass.getpass(f"  {prompt}: ")
        if not value:
            print("    a value is required")
            continue
        problem = check(value) if check else None
        if problem:
            print(f"    {problem}")
            continue
        if confirm and getpass.getpass("  repeat to confirm: ") != value:
            print("    the two entries differ")
            continue
        return value


