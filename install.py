def tls_context(verify_hostname=True, verify_chain=True):
    ctx = ssl.create_default_context(cafile=CA) if CA else ssl.create_default_context()
    if not verify_chain:
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
    elif not verify_hostname:
        ctx.check_hostname = False
    return ctx


# --------------------------------------------------------------------------- PostgreSQL
class PgError(Exception):
    pass


def _pg_read(sock):
    head = _recv_exact(sock, 5)
    kind, length = head[:1], struct.unpack("!I", head[1:])[0]
    return kind, _recv_exact(sock, length - 4)


def _recv_exact(sock, n):
    buf = b""
    while len(buf) < n:
        chunk = sock.recv(n - len(buf))
        if not chunk:
            raise PgError("server closed the connection")
        buf += chunk
    return buf


def _pg_send(sock, kind, payload):
    sock.sendall(kind + struct.pack("!I", len(payload) + 4) + payload)


def _pg_error_text(body):
    fields = {}
    for part in body.split(b"\x00"):
        if part:
            fields[part[:1].decode()] = part[1:].decode(errors="replace")
    return f"{fields.get('S', 'ERROR')} {fields.get('C', '')}: {fields.get('M', '')}".strip()


def scram_client_final(password, client_first_bare, server_first, client_nonce):
    """RFC 5802 / 7677 SCRAM-SHA-256 client-final-message (no channel binding)."""
    attrs = dict(item.split("=", 1) for item in server_first.split(","))
    nonce, salt, iterations = attrs["r"], base64.b64decode(attrs["s"]), int(attrs["i"])
    if not nonce.startswith(client_nonce):
        raise PgError("SCRAM nonce mismatch")
    salted = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, iterations)
    client_key = hmac.new(salted, b"Client Key", hashlib.sha256).digest()
    stored_key = hashlib.sha256(client_key).digest()
    without_proof = f"c=biws,r={nonce}"
    auth_message = f"{client_first_bare},{server_first},{without_proof}".encode()
    signature = hmac.new(stored_key, auth_message, hashlib.sha256).digest()
    proof = bytes(a ^ b for a, b in zip(client_key, signature))
    return f"{without_proof},p={base64.b64encode(proof).decode()}"


def _pg_authenticate(sock, user, password):
    while True:
        kind, body = _pg_read(sock)
        if kind == b"E":
            raise PgError(_pg_error_text(body))
        if kind != b"R":
            continue
        code = struct.unpack("!I", body[:4])[0]
        if code == 0:                       # AuthenticationOk: drain ParameterStatus/BackendKeyData
            while True:
                kind, body = _pg_read(sock)
                if kind == b"E":
                    raise PgError(_pg_error_text(body))
                if kind == b"Z":            # ReadyForQuery
                    return
        if code == 3:                       # cleartext
            _pg_send(sock, b"p", password.encode() + b"\x00")
        elif code == 5:                     # MD5
            inner = hashlib.md5((password + user).encode()).hexdigest()
            outer = hashlib.md5(inner.encode() + body[4:8]).hexdigest()
            _pg_send(sock, b"p", b"md5" + outer.encode() + b"\x00")
        elif code == 10:                    # SASL
            mechanisms = [m for m in body[4:].split(b"\x00") if m]
            if b"SCRAM-SHA-256" not in mechanisms:
                raise PgError(f"unsupported SASL mechanisms {mechanisms}")
            client_nonce = base64.b64encode(secrets.token_bytes(18)).decode()
            first_bare = f"n=,r={client_nonce}"
            first = ("n,," + first_bare).encode()
            _pg_send(sock, b"p", b"SCRAM-SHA-256\x00" + struct.pack("!I", len(first)) + first)
            kind, body = _pg_read(sock)
            if kind == b"E":
                raise PgError(_pg_error_text(body))
            if kind != b"R" or struct.unpack("!I", body[:4])[0] != 11:
                raise PgError("unexpected reply to SCRAM client-first message")
            server_first = body[4:].decode()
            final = scram_client_final(password, first_bare, server_first, client_nonce)
            _pg_send(sock, b"p", final.encode())
        elif code in (11, 12):              # SASLContinue / SASLFinal handled inline
            continue
        else:
            raise PgError(f"unsupported authentication method code {code}")


def _pg_query_row(sock, sql):
    _pg_send(sock, b"Q", sql.encode() + b"\x00")
    row = None
    while True:
        kind, body = _pg_read(sock)
        if kind == b"E":
            raise PgError(_pg_error_text(body))
        if kind == b"D":
            count = struct.unpack("!H", body[:2])[0]
            pos, row = 2, []
            for _ in range(count):
                size = struct.unpack("!i", body[pos:pos + 4])[0]
                pos += 4
                if size < 0:
                    row.append(None)
                else:
                    row.append(body[pos:pos + size].decode())
                    pos += size
        if kind == b"Z":
            return row


def probe_postgres():
    url = urllib.parse.urlsplit(os.environ.get("DATABASE_URL", ""))
    host, port = url.hostname, url.port or 5432
    user = urllib.parse.unquote(url.username or "")
    password = urllib.parse.unquote(url.password or "")
    database = url.path.lstrip("/") or user
    sslmode = urllib.parse.parse_qs(url.query).get("sslmode", ["prefer"])[0]
    try:
        socket.getaddrinfo(host, port)
    except OSError as exc:
        return emit("postgres.dns", False, f"{host}: {exc}")
    try:
        sock = socket.create_connection((host, port), timeout=TIMEOUT)
    except OSError as exc:
        return emit("postgres.tcp", False, f"{host}:{port}: {exc} (firewall?)")
    emit("postgres.tcp", True, f"{host}:{port} reachable")
    try:
        if sslmode in ("require", "verify-ca", "verify-full"):
            sock.sendall(struct.pack("!II", 8, 80877103))
            if _recv_exact(sock, 1) != b"S":
                raise PgError("server does not accept TLS")
            ctx = tls_context(verify_hostname=(sslmode == "verify-full"),
                              verify_chain=(sslmode != "require"))
            sock = ctx.wrap_socket(sock, server_hostname=host)
            emit("postgres.tls", True, f"{sock.version()}, certificate verified ({sslmode})")
        startup = b"user\x00" + user.encode() + b"\x00database\x00" + database.encode() + b"\x00\x00"
        sock.sendall(struct.pack("!II", len(startup) + 8, 196608) + startup)
        _pg_authenticate(sock, user, password)
        emit("postgres.login", True, f"logged in as {user} to {database}")
        row = _pg_query_row(sock, (
            "select pg_is_in_recovery()::text, current_setting('server_version'), "
            "has_database_privilege(current_user, current_database(), 'CREATE')::text, "
            "coalesce(has_schema_privilege('public', 'CREATE'), false)::text"))
        recovery, version, db_create, schema_create = row
        emit("postgres.primary", recovery == "false",
             "writable primary" if recovery == "false" else "connected to a READ-ONLY replica")
        emit("postgres.version", True, f"PostgreSQL {version}")
        emit("postgres.create", schema_create == "true",
             "can create tables in schema public" if schema_create == "true"
             else "role cannot CREATE in schema public - migrations will fail (make it the owner)")
        _ = db_create
    except ssl.SSLError as exc:
        emit("postgres.tls", False, f"{exc} (CA bundle / hostname?)")
    except (PgError, OSError) as exc:
        emit("postgres.login", False, exc)
    finally:
        try:
            sock.close()
        except OSError:
            pass


# --------------------------------------------------------------------------- Redis
def probe_redis(spec):
    try:
        import redis
    except ImportError as exc:
        return emit("redis.client", False, f"redis-py not in image: {exc}")
    r = spec["redis"]
    common = {"socket_timeout": TIMEOUT, "socket_connect_timeout": TIMEOUT,
              "password": os.environ.get("REDIS_PASSWORD") or None}
    if r.get("username"):
        common["username"] = r["username"]
    if r.get("tls"):
        common["ssl"] = True
        if CA:
            common["ssl_ca_certs"] = CA
    topology = r["topology"]
    try:
        for host, port in r["nodes"]:
            socket.create_connection((host, int(port)), timeout=TIMEOUT).close()
        emit("redis.tcp", True, ", ".join(f"{h}:{p}" for h, p in r["nodes"]) + " reachable")
    except OSError as exc:
        return emit("redis.tcp", False, f"{exc} (firewall?)")
    try:
        if topology == "standalone":
            host, port = r["nodes"][0]
            client = redis.Redis(host=host, port=int(port), **common)
        elif topology == "sentinel":
            from redis.sentinel import Sentinel
            sentinel_kwargs = {"socket_timeout": TIMEOUT}
            if os.environ.get("REDIS_SENTINEL_PASSWORD"):
                sentinel_kwargs["password"] = os.environ["REDIS_SENTINEL_PASSWORD"]
            if r.get("tls"):
                sentinel_kwargs["ssl"] = True
                if CA:
                    sentinel_kwargs["ssl_ca_certs"] = CA
            sentinel = Sentinel([(h, int(p)) for h, p in r["nodes"]], sentinel_kwargs=sentinel_kwargs, **common)
            master = sentinel.discover_master(r["service_name"])
            emit("redis.sentinel", True, f"master '{r['service_name']}' is {master[0]}:{master[1]}")
            client = sentinel.master_for(r["service_name"], **common)
        else:
            from redis.cluster import ClusterNode, RedisCluster
            client = RedisCluster(startup_nodes=[ClusterNode(h, int(p)) for h, p in r["nodes"]], **common)
        client.ping()
        info = client.info("server")
        if topology == "cluster":           # RedisCluster.info returns one dict per node
            info = next(iter(info.values())) if info and isinstance(next(iter(info.values())), dict) else info
        version = info.get("redis_version", "?")
        mode = info.get("redis_mode", "?")
        major = int(str(version).split(".")[0]) if str(version)[:1].isdigit() else 0
        emit("redis.version", major >= 7, f"Redis {version} (needs 7.0+), mode {mode}")
        expected = "cluster" if topology == "cluster" else "standalone"
        emit("redis.topology", mode == expected, f"server reports '{mode}', installer configured '{topology}'")
        key = "litellm:installer-probe"
        client.set(key, "1", ex=30)
        client.get(key)
        client.delete(key)
        client.publish("litellm:installer-probe", "ping")
        emit("redis.acl", True, "read/write on litellm:* keys and publish on litellm:* channels")
    except Exception as exc:  # noqa: BLE001 - report any client error verbatim
        emit("redis.login", False, f"{type(exc).__name__}: {exc}")


# --------------------------------------------------------------------------- model servers
def probe_models(urls):
    for base in urls:
        target = base.rstrip("/") + "/models"
        try:
            ctx = tls_context() if target.startswith("https") else None
            with urllib.request.urlopen(target, timeout=TIMEOUT, context=ctx) as resp:
                emit("model." + base, True, f"HTTP {resp.status}")
        except urllib.error.HTTPError as exc:
            emit("model." + base, True, f"reachable, HTTP {exc.code} (auth is added per model in the UI)")
        except Exception as exc:  # noqa: BLE001
            emit("model." + base, False, f"{getattr(exc, 'reason', exc)}")


