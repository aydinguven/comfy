def firewall_rule(cidr, port):
    family = "ipv6" if ":" in cidr else "ipv4"
    return f'rule family="{family}" source address="{cidr}" port port="{port}" protocol="tcp" accept'


def apply_firewall(a, state, facts):
    step("Firewall")
    wanted = sorted({firewall_rule(c, a["host_port"]) for c in a["lb_cidrs"] + a["admin_cidrs"]})
    if not facts["firewalld"]:
        note("firewalld is not active: restrict port %s to %s another way" % (a["host_port"], ", ".join(a["lb_cidrs"])))
        return
    for rule in wanted:
        run(["firewall-cmd", "--permanent", f"--add-rich-rule={rule}"])
    for rule in set(state.get("firewall_rules", [])) - set(wanted):
        run(["firewall-cmd", "--permanent", f"--remove-rich-rule={rule}"], check=False)
    run(["firewall-cmd", "--reload"])
    state["firewall_rules"] = wanted
    good(f"port {a['host_port']}/tcp open only to " + ", ".join(a["lb_cidrs"] + a["admin_cidrs"]))


