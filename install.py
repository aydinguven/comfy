# ============================================================================ validators
_HOST_RE = re.compile(r"^(?=.{1,253}$)([A-Za-z0-9_-]{1,63}\.)*[A-Za-z0-9_-]{1,63}$")


def split_list(value):
    return [item.strip() for item in str(value).split(",") if item.strip()]


def v_host(value):
    try:
        ipaddress.ip_address(value)
        return None
    except ValueError:
        return None if _HOST_RE.match(value) else "not a valid host name or IP address"


def v_int(low, high):
    def check(value):
        if not value.isdigit() or not low <= int(value) <= high:
            return f"enter a number between {low} and {high}"
        return None
    return check


def v_cidrs(value):
    for item in split_list(value):
        try:
            ipaddress.ip_network(item, strict=False)
        except ValueError:
            return f"'{item}' is not a CIDR range such as 10.20.30.0/28"
    return None if split_list(value) else "enter at least one range"


def v_cidrs_optional(value):
    return v_cidrs(value) if value else None


def v_hostports(value):
    for item in split_list(value):
        host, _, port = item.rpartition(":")
        if not host or v_host(host.strip("[]")) or not port.isdigit():
            return f"'{item}' is not host:port"
    return None if split_list(value) else "enter at least one host:port"


def parse_hostports(value):
    pairs = []
    for item in split_list(value):
        host, _, port = item.rpartition(":")
        pairs.append([host.strip("[]"), int(port)])
    return pairs


def v_ident(value):
    return None if re.match(r"^[A-Za-z0-9_.-]+$", value) else "letters, digits, '_', '.', '-' only"


def v_retention(value):
    return None if re.match(r"^[0-9]+[smhdw]$", value) else "use a number plus unit, e.g. 30d, 90d, 12w"


def v_pem_cert(value):
    path = Path(value)
    if not path.is_file():
        return "file not found"
    return None if "-----BEGIN CERTIFICATE-----" in path.read_text(errors="replace") else "no PEM certificate in that file"


def v_pem_key(value):
    path = Path(value)
    if not path.is_file():
        return "file not found"
    return None if "PRIVATE KEY-----" in path.read_text(errors="replace") else "no PEM private key in that file"


def v_urls(value):
    for item in split_list(value):
        if not re.match(r"^https?://[^\s/]+", item):
            return f"'{item}' must start with http:// or https://"
    return None


def v_master_key(value):
    return None if value.startswith("sk-") and len(value) >= 35 else "must start with sk- and be long (sk- + 32+ characters)"


def fingerprint(value):
    """Short non-reversible fingerprint used to check that every node got the same key."""
    return hashlib.sha256(("litellm-gateway-fp:" + value).encode()).hexdigest()[:16]


# ============================================================================ commands (subprocess)
def _user():
    import pwd  # POSIX only; imported lazily so the module can be inspected elsewhere
    return pwd.getpwnam(SERVICE_USER)


def user_exists():
    try:
        _user()
        return True
    except KeyError:
        return False


def user_cmd(cmd):
    entry = _user()
    return ["runuser", "-u", SERVICE_USER, "--", "env", f"HOME={entry.pw_dir}",
            f"XDG_RUNTIME_DIR=/run/user/{entry.pw_uid}"] + list(cmd)


def run(cmd, check=True, stdin=None, interactive=False, as_user=False, quiet=False, timeout=None,
        env=None, cwd=None):
    """Run a command. Secrets travel only through stdin or env and are never logged."""
    if as_user:
        cmd = user_cmd(cmd)
    log("$ " + shlex.join(cmd))
    cwd = cwd or ("/" if as_user else None)
    try:
        if interactive:
            sys.stdout.flush()
            result = subprocess.run(cmd, cwd=cwd, timeout=timeout, env=env)
            result.stdout = result.stderr = ""
        else:
            result = subprocess.run(cmd, input=stdin, capture_output=True, text=True, cwd=cwd, timeout=timeout,
                                    env=env)
            if not quiet:
                log(result.stdout[-6000:])
                log(result.stderr[-6000:])
    except subprocess.TimeoutExpired:
        die(f"timed out after {timeout} s: {shlex.join(cmd)}")
    if check and result.returncode != 0:
        detail = (result.stderr + "\n" + result.stdout).strip()[-2000:] if not quiet else ""
        die(f"command failed (exit {result.returncode}): {shlex.join(cmd)}\n{detail}")
    return result


def podman(*args, **kwargs):
    return run(["podman"] + list(args), as_user=True, **kwargs)


def user_systemctl(*args, check=True):
    return run(["systemctl", "--user", "-M", f"{SERVICE_USER}@"] + list(args), check=check)


def podman_version():
    if not shutil.which("podman"):
        return None
    match = re.search(r"(\d+)\.(\d+)\.(\d+)", run(["podman", "--version"], check=False).stdout)
    return tuple(int(part) for part in match.groups()) if match else None


def runtime_ready():
    """True when rootless Podman can be used for the service user right now."""
    if not user_exists() or not shutil.which("podman"):
        return False
    return Path(f"/run/user/{_user().pw_uid}").is_dir()


def read_env_file(path):
    """Parse a systemd-style KEY=VALUE file (double quotes with \\\\ and \\" escapes)."""
    values = {}
    try:
        lines = Path(path).read_text().splitlines()
    except OSError:
        return values
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        if len(value) >= 2 and value[0] == value[-1] == '"':
            value = re.sub(r"\\(.)", r"\1", value[1:-1])
        values[key.strip()] = value
    return values


def write_secret_file(values):
    body = "# Generated by install.py - root only; read by systemd for the native gateway.\n"
    for key in sorted(values):
        escaped = values[key].replace("\\", "\\\\").replace('"', '\\"')
        body += f'{key}="{escaped}"\n'
    write_file(SECRETS_FILE, body, mode=0o600, owner=False)


def existing_secrets():
    if mode() == "native":
        values = read_env_file(SECRETS_FILE)
        return {name for name, var in SECRET_ENV.items() if values.get(var)}
    if not runtime_ready():
        return set()
    result = podman("secret", "ls", "--format", "{{.Name}}", check=False)
    return set(result.stdout.split()) if result.returncode == 0 else set()


def read_secret(name):
    if mode() == "native":
        return read_env_file(SECRETS_FILE).get(SECRET_ENV[name]) or None
    result = podman("secret", "inspect", "--showsecret", "--format", "{{.SecretData}}", name,
                    check=False, quiet=True)
    return result.stdout.rstrip("\n") if result.returncode == 0 and result.stdout.strip() else None


def store_secret(name, value):
    if mode() == "native":
        values = read_env_file(SECRETS_FILE)
        values[SECRET_ENV[name]] = value
        write_secret_file(values)
        return
    podman("secret", "rm", name, check=False, quiet=True)
    podman("secret", "create", name, "-", stdin=value, quiet=True)


def service_active():
    if mode() == "native":
        return run(["systemctl", "is-active", UNIT], check=False).stdout.strip() == "active"
    return runtime_ready() and user_systemctl("is-active", UNIT, check=False).stdout.strip() == "active"


