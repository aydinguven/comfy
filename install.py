def ensure_image(rel, state):
    step("Container image")
    meta = image_meta(rel)
    tag, want = meta["local_tag"], meta["image_id"]
    if podman("image", "exists", tag, check=False).returncode == 0:
        got = podman("image", "inspect", "--format", "{{.Id}}", tag).stdout.strip()
        if got != want:
            die(f"{tag} already exists with a different image ID ({got[:12]}). Remove it: "
                f"runuser -u {SERVICE_USER} -- podman rmi {tag}")
        good(f"{tag} already loaded")
    else:
        archive = rel["dirs"]["image"] / meta["archive"]
        need = image_space_gib(meta)
        store = SRV / "containers" if state.get("storage_path") == "srv" else Path(_user().pw_dir)
        free = free_gib(store)
        if free < need:
            note(f"only {free:.1f} GiB free at {store}; loading needs about {need:.0f} GiB")
            if not ask_yes("Try anyway?", False):
                die("free up space (or remove old images: runuser -u litellm -- podman image prune -a)")
        print(f"  loading {archive.name} ({archive.stat().st_size / 2**30:.1f} GiB)...", flush=True)
        log("$ podman load < " + str(archive))
        with open(archive, "rb") as fh:   # streamed via stdin: the service user needs no access to the part
            result = subprocess.run(user_cmd(["podman", "load"]), stdin=fh, capture_output=True, text=True, cwd="/")
        log(result.stdout + result.stderr)
        if result.returncode != 0:
            die("podman load failed:\n" + result.stderr.strip()[-1500:])
        if podman("image", "exists", want, check=False).returncode != 0:
            die(f"after loading, no image with ID {want[:12]} exists - the archive does not match the manifest")
        podman("tag", want, tag)
        got = podman("image", "inspect", "--format", "{{.Id}}", tag).stdout.strip()
        if got != want:
            die(f"{tag} has image ID {got[:12]}, the manifest says {want[:12]}")
        good(f"{tag} loaded, image ID {want[:12]} matches the manifest")
    scan_image(tag)
    return tag


def scan_image(tag):
    cid = podman("create", "--pull=never", tag).stdout.strip()
    hits = []
    try:
        proc = subprocess.Popen(user_cmd(["podman", "export", cid]), stdout=subprocess.PIPE,
                                stderr=subprocess.DEVNULL, cwd="/")
        with tarfile.open(fileobj=proc.stdout, mode="r|") as archive:
            for member in archive:
                if PAYLOAD_RE.search(member.name):
                    hits.append(member.name)
        proc.wait()
    finally:
        podman("rm", "-f", cid, check=False)
    if hits:
        die("the image contains the Oct-2026 malware files: " + ", ".join(hits))
    good("filesystem scan: no cook.pth / cook.py / sitecustomize.py in site-packages")


