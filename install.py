def venv_site(release, nm):
    return Path(release) / "venv" / "lib" / f"python{nm['python']}" / "site-packages"


def native_release_id(rel):
    """Changes whenever any input of the release changes, whichever bundle the parts came from."""
    dirs, prisma = rel["dirs"], rel["parts"]["prisma"]["meta"]
    digest = hashlib.sha256()
    for path in (dirs["python"] / "requirements.txt", dirs["litellm"] / "requirements.txt",
                 dirs["litellm"] / "enterprise.tar"):
        digest.update(sha256_file(path).encode())
    digest.update((prisma["client_id"] + prisma["engine_hash"] + prisma["engine_platform"]).encode())
    return digest.hexdigest()


def ensure_native_release(rel):
    step("Native release")
    nm, dirs = native_info(rel), rel["dirs"]
    release = release_dir(rel)
    marker = release / ".complete"
    release_id = native_release_id(rel)
    if marker.exists() and load_json(marker).get("release_id") == release_id:
        good(f"{release} already installed")
        return release
    if release.exists():
        if NATIVE_CURRENT.is_symlink() and NATIVE_CURRENT.resolve() == release.resolve():
            die(f"{release} is the running release but was built from different parts "
                f"({', '.join(load_json(marker).get('parts', [])) or 'unknown'}). Use those parts, "
                "or roll back / switch to another release before rebuilding it")
        note(f"removing an incomplete or different earlier build at {release}")
        shutil.rmtree(release)
    release.mkdir(parents=True)
    python = shutil.which(f"python{nm['python']}")
    print("  creating the virtual environment...", flush=True)
    run([python, "-m", "venv", str(release / "venv")])
    vpython = str(release / "venv" / "bin" / "python")
    print(f"  installing {nm['packages']} pinned wheels offline (every file hash-checked)...", flush=True)
    run([vpython, "-m", "pip", "install", "--no-index", "--no-deps", "--require-hashes", "--no-cache-dir",
         "--disable-pip-version-check", "--no-input",
         "--find-links", str(dirs["python"] / "wheels"), "--find-links", str(dirs["litellm"] / "wheels"),
         "-r", str(dirs["python"] / "requirements.txt"), "-r", str(dirs["litellm"] / "requirements.txt")],
        timeout=3600)
    site = venv_site(release, nm)
    hits = [p.name for p in site.iterdir() if p.name in ("cook.pth", "cook.py", "sitecustomize.py")]
    if hits:
        die("the 21 Oct payload files appeared in the venv: " + ", ".join(hits))
    print("  adding the Prisma client generated for LiteLLM's schema, the Prisma CLI and RHEL engines...", flush=True)
    shutil.rmtree(site / "prisma", ignore_errors=True)
    safe_extract(dirs["prisma"] / "prisma-client.tar", site)
    safe_extract(dirs["prisma"] / "prisma-cli.tar", release / "prisma" / "binaries")
    (release / "prisma" / "binaries" / "package.json").write_text(json.dumps(PRISMA_PACKAGE_JSON))
    engines = release / "prisma" / "engines"
    engines.mkdir(parents=True, exist_ok=True)
    for engine in (dirs["prisma"] / "engines").iterdir():
        shutil.copy2(engine, engines / engine.name)
        os.chmod(engines / engine.name, 0o755)
    safe_extract(dirs["litellm"] / "enterprise.tar", release / "app")
    print("  precompiling Python files...", flush=True)
    run([vpython, "-m", "compileall", "-q", "-j", "0", str(site)], check=False, timeout=1800)
    check = run([vpython, "-m", "pip", "check"], check=False)
    if check.returncode != 0:
        note("pip check reports: " + check.stdout.strip()[-600:])
    for engine in engines.iterdir():
        result = run([str(engine), "--version"], check=False)
        if result.returncode != 0:
            die(f"{engine.name} does not run on this node:\n{(result.stderr or result.stdout).strip()[-800:]}")
        good(f"{result.stdout.strip()} runs on this node")
    save_json(marker, {"version": rel["version"], "python": nm["python"], "engine_platform": nm["engine_platform"],
                       "release_id": release_id, "parts": sorted(p["name"] for p in rel["parts"].values()),
                       "installed_at": datetime.datetime.now().isoformat(timespec="seconds")})
    good(f"release ready at {release}")
    return release


