def database_url(a, password):
    host = f"[{a['pg_host']}]" if ":" in a["pg_host"] else a["pg_host"]
    url = (f"postgresql://{urllib.parse.quote(a['pg_user'], safe='')}:{urllib.parse.quote(password, safe='')}"
           f"@{host}:{a['pg_port']}/{a['pg_db']}")
    params = {}
    if a["pg_sslmode"] != "disable":
        params["sslmode"] = a["pg_sslmode"]
    if a["pg_sslmode"] in ("verify-full", "verify-ca"):
        params["sslrootcert"] = ca_path()
    return url + ("?" + urllib.parse.urlencode(params, safe="/") if params else "")


