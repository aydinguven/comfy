def local_opener(tls):
    handlers = [urllib.request.ProxyHandler({})]   # never send loopback checks through an HTTP proxy
    if tls:
        context = ssl.create_default_context()
        context.check_hostname = False            # loopback check only; the LB validates the real cert
        context.verify_mode = ssl.CERT_NONE
        handlers.append(urllib.request.HTTPSHandler(context=context))
    return urllib.request.build_opener(*handlers)


def local_url(a, path):
    return f"{'https' if a['node_tls'] else 'http'}://127.0.0.1:{a['host_port']}{path}"


def wait_ready(a, timeout=480):
    opener, url = local_opener(a["node_tls"]), local_url(a, "/health/readiness")
    print("  waiting for /health/readiness", end="", flush=True)
    deadline, last = time.time() + timeout, "no answer yet"
    while time.time() < deadline:
        try:
            with opener.open(url, timeout=5) as resp:
                print()
                body = resp.read().decode(errors="replace")
                good(f"ready: {body.strip()[:200]}")
                return True
        except urllib.error.HTTPError as exc:
            last = f"HTTP {exc.code}"
        except OSError as exc:
            last = str(getattr(exc, "reason", exc))
        print(".", end="", flush=True)
        time.sleep(5)
    print()
    bad(f"not ready after {timeout} s (last: {last})")
    return False


