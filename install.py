def download_parts(chosen_mode, version):
    """Run the verified downloader for this node's mode/arch/version; returns the part folders it built."""
    step(f"Downloading the {chosen_mode} parts of LiteLLM {version} (all checks of build_bundle.py apply)")
    if version.lstrip("v") in ("1.107.0",):
        die(f"{version} is the compromised release")
    source, origin = builder_source()
    base = DOWNLOAD["dir"]
    base.mkdir(parents=True, exist_ok=True)
    os.chmod(base, 0o700)
    need, free = ONLINE_SPACE_GIB[chosen_mode], free_gib(base)
    if free < need:
        note(f"only {free:.1f} GiB free at {base}; the download needs about {need:.1f} GiB")
        if not ask_yes("Try anyway?", False):
            die("free some space, or choose another place with --download-dir")
    builder = base / "build_bundle.py"
    builder.write_bytes(source)
    arch = {"x86_64": "amd64", "aarch64": "arm64"}.get(platform.machine())
    if not arch:
        die(f"no LiteLLM image for this CPU ({platform.machine()})")
    out = base / f"litellm-ha-bundle-{version}-{arch}"
    python = builder_python(chosen_mode)
    say(f"  downloader: {origin}, run with {python}; parts go to {out / 'parts'}")
    cmd = [python, str(builder), "--version", version, "--parts", ONLINE_PARTS[chosen_mode], "--arch", arch,
           "--python", NATIVE_PYTHON, "--out", str(out), "--cache", str(base / "cache"), "--pack", "none",
           "--clean-cache"]
    result = run(cmd, interactive=True, check=False, env=online_env(), cwd=str(base))
    if result.returncode != 0:
        die("downloading or verifying the parts failed (see above) - nothing was installed. Behind a proxy? "
            "Use --proxy http://proxy:port (sudo drops HTTPS_PROXY). Test the connection with: "
            f"{python} {builder} --check-network [--proxy URL]")
    built = []
    for kind in ONLINE_PARTS[chosen_mode].split(","):
        python_tag = f"-py{NATIVE_PYTHON}" if kind in ("python", "litellm") else ""
        folder = out / "parts" / f"part-{kind}-{version}{python_tag}-{arch}"
        if not (folder / "PART.json").is_file():
            die(f"the downloader did not produce {folder.name}")
        built.append(folder)
    good(f"downloaded and verified: {', '.join(f.name for f in built)}")
    say(f"  They stay in {out} - copy that folder to the other nodes to install them offline.")
    SOURCES["paths"].append(str(out))
    SOURCES["pins"] += [str(f) for f in built]
    SOURCES["version"] = version
    return built


