def os_release():
    data = {}
    for line in Path("/etc/os-release").read_text().splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            data[key] = value.strip().strip('"')
    return data


def mem_gib():
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith("MemTotal:"):
            return int(line.split()[1]) / 2**20
    return 0.0


def preflight(rel):
    step("Checking this node")
    osr = os_release()
    name = f"{osr.get('NAME', '?')} {osr.get('VERSION_ID', '?')}"
    if osr.get("ID") == "rhel" and osr.get("VERSION_ID", "").startswith("9."):
        good(name)
    else:
        note(f"{name} - this installer is built for RHEL 9")
        if not ask_yes("Continue anyway?", False):
            die("stopped by the operator")

    machine = platform.machine()
    if machine != PLATFORM_ARCH.get(rel["platform"]):
        die(f"this node is {machine}, the parts are for {rel['platform']} - build them with the right --arch")
    good(f"architecture {machine}")

    cpus, memory = os.cpu_count() or 1, mem_gib()
    (good if memory >= 7.5 else note)(f"{cpus} vCPU, {memory:.1f} GiB RAM (each worker wants 1 vCPU + 4 GiB)")

    userns_path = Path("/proc/sys/user/max_user_namespaces")
    userns = int(userns_path.read_text()) if userns_path.exists() else 0
    if mode() == "native":
        pass
    elif userns >= 1000:
        good(f"user namespaces available ({userns})")
    else:
        note(f"user.max_user_namespaces={userns}: rootless Podman needs user namespaces")
        if not ask_yes("Set user.max_user_namespaces=15000 (persisted in /etc/sysctl.d/90-litellm-userns.conf)?", True):
            die("rootless Podman cannot run without user namespaces")
        Path("/etc/sysctl.d/90-litellm-userns.conf").write_text("user.max_user_namespaces = 15000\n")
        run(["sysctl", "-w", "user.max_user_namespaces=15000"])
        good("user namespaces enabled")

    selinux = run(["getenforce"], check=False).stdout.strip() if shutil.which("getenforce") else "not installed"
    (good if selinux == "Enforcing" else note)(f"SELinux {selinux}")
    fips = Path("/proc/sys/crypto/fips_enabled")
    if fips.exists() and fips.read_text().strip() == "1":
        note("FIPS mode is on - the LiteLLM image is not FIPS-validated; confirm this is acceptable")
    chrony = run(["chronyc", "tracking"], check=False).stdout if shutil.which("chronyc") else ""
    if re.search(r"Leap status\s*:\s*Normal", chrony):
        good("clock synchronised (chrony)")
    else:
        note("chrony is not synchronised - TLS certificate checks need a correct clock")
    firewalld = run(["systemctl", "is-active", "firewalld"], check=False).stdout.strip() == "active"
    (good if firewalld else note)("firewalld " + ("active" if firewalld else "not active - the node port will not be restricted"))
    version = podman_version()
    if mode() == "native":
        nm = native_info(rel)
        python = f"python{nm['python']}"
        (good if shutil.which(python) else note)(
            f"{python} " + ("found" if shutil.which(python) else "missing - it will be installed from Satellite"))
        node = node_version()
        (good if node and node >= MIN_NODE else note)(
            f"Node.js {node[0]}.{node[1]}" if node else "Node.js missing - it will be installed from Satellite")
    elif version is None:
        note("Podman is not installed - it will be installed from this node's Satellite repositories")
    else:
        (good if version >= MIN_PODMAN else note)(f"Podman {'.'.join(map(str, version))}")
    return {"cpus": cpus, "mem_gib": memory, "podman": version, "firewalld": firewalld}


