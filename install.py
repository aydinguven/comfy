def version_key(version):
    return tuple(int(n) for n in re.findall(r"\d+", version or "")) or (0,)


def _part(meta, where, folder=None, tar=None, prefix=""):
    return {"name": meta["name"], "kind": meta["part"], "meta": meta, "dir": folder, "tar": tar,
            "prefix": prefix, "where": where}


def _valid_meta(meta):
    return (isinstance(meta, dict) and meta.get("format") == PART_FORMAT and isinstance(meta.get("name"), str)
            and meta.get("part") in ("image", "python", "litellm", "prisma", "installer"))


def _scan_tar(path, found):
    try:
        with tarfile.open(path) as tar:
            for member in tar:
                name = member.name[2:] if member.name.startswith("./") else member.name
                if member.isfile() and (name == "PART.json" or name.endswith("/PART.json")) and name.count("/") <= 3:
                    try:
                        meta = json.loads(tar.extractfile(member).read().decode())
                    except ValueError:
                        continue
                    if _valid_meta(meta):
                        found.append(_part(meta, f"{path} : {name[:-len('PART.json')] or './'}",
                                           tar=path, prefix=name[:-len("PART.json")]))
    except (tarfile.TarError, OSError) as exc:
        log(f"skipping {path}: {exc}")


def search_roots():
    roots, seen = [], set()
    for root in [HERE, Path.cwd()] + [Path(p) for p in SOURCES["paths"]]:
        resolved = root.resolve()
        if resolved not in seen:
            seen.add(resolved)
            roots.append(resolved)
    return roots


def discover_parts():
    """Every part in the search roots: folders with PART.json (also in parts/ subfolders) and tars."""
    found = []
    for root in search_roots():
        if root.is_file():
            _scan_tar(root, found)
            continue
        if not root.is_dir():
            note(f"{root} does not exist")
            continue
        try:
            folders = [root] + sorted(root.glob("*")) + sorted(root.glob("parts/*")) + sorted(root.glob("*/parts/*"))
            tars = sorted(root.glob("*.tar"))
        except OSError as exc:
            note(f"cannot read {root}: {exc}")
            continue
        for folder in folders:
            try:
                is_part = folder.is_dir() and (folder / "PART.json").is_file()
            except OSError:                            # unreadable folders (e.g. under /tmp) are skipped
                continue
            if is_part:
                meta = load_json(folder / "PART.json")
                if _valid_meta(meta):
                    found.append(_part(meta, str(folder), folder=folder))
        for tar in tars:
            _scan_tar(tar, found)
    unique = {}
    for item in found:                                 # the same part in several places: prefer a folder
        known = unique.get(item["name"])
        if known is None or (known["dir"] is None and item["dir"] is not None):
            unique[item["name"]] = item
    return list(unique.values())


def apply_pins(parts):
    """--part NAME|PATH: only the pinned parts are candidates for their kind."""
    pinned = {}
    for pin in SOURCES["pins"]:
        path = Path(pin)
        if path.exists():
            resolved, matches = path.resolve(), []
            for item in parts:
                if (item["dir"] and item["dir"].resolve() == resolved) or (item["tar"] and item["tar"].resolve() == resolved):
                    matches.append(item)
        else:
            matches = [item for item in parts if item["name"] == pin or item["name"] == "part-" + pin]
        if not matches:
            die(f"--part {pin}: no such part found (see: install.py parts)")
        for item in matches:
            pinned.setdefault(item["kind"], set()).add(item["name"])
    return [item for item in parts if item["kind"] not in pinned or item["name"] in pinned[item["kind"]]]


def assemble_releases(parts, platform_name):
    """Complete or incomplete sets the installer could deploy, for one platform."""
    usable = [p for p in parts if p["meta"].get("platform") == platform_name]
    releases = []
    for image in (p for p in usable if p["kind"] == "image"):
        releases.append({"mode": "container", "version": image["meta"]["litellm_version"], "platform": platform_name,
                         "parts": {"image": image}, "missing": []})
    for app in (p for p in usable if p["kind"] == "litellm"):
        meta, need = app["meta"], app["meta"].get("requires", {})
        rel = {"mode": "native", "version": meta["litellm_version"], "platform": platform_name,
               "python": meta.get("python"), "parts": {"litellm": app}, "missing": []}
        python_need, prisma_need = need.get("python", {}), need.get("prisma", {})
        options = {
            "python": [p for p in usable if p["kind"] == "python" and p["meta"].get("python") == meta.get("python")
                       and p["meta"].get("deps_id") == python_need.get("deps_id")],
            "prisma": [p for p in usable if p["kind"] == "prisma"
                       and p["meta"].get("client_id") == prisma_need.get("client_id")
                       and p["meta"].get("engine_hash") == prisma_need.get("engine_hash")],
        }
        for kind, choices in options.items():
            if not choices:
                ident = python_need.get("deps_id") if kind == "python" else prisma_need.get("client_id")
                rel["missing"].append(f"a {kind} part with id {str(ident)[:12]} (e.g. build_bundle.py --version "
                                      f"{meta['litellm_version']} --parts {kind}"
                                      + (f" --python {meta.get('python')}" if kind == "python" else "") + ")")
                continue
            # prefer the part built from the same release, then a folder over a tar, then the newest
            choices.sort(key=lambda p: (p["meta"]["litellm_version"] == rel["version"], p["dir"] is not None,
                                        version_key(p["meta"]["litellm_version"])), reverse=True)
            rel["parts"][kind] = choices[0]
        releases.append(rel)
    releases.sort(key=lambda r: version_key(r["version"]), reverse=True)
    return releases


def release_label(rel):
    names = ", ".join(rel["parts"][k]["name"] for k in RELEASE_KINDS[rel["mode"]] if k in rel["parts"])
    extra = f", Python {rel['python']}" if rel["mode"] == "native" else ""
    return f"LiteLLM {rel['version']} {rel['mode']}{extra}  [{names}]"


def find_releases(want_mode=None):
    """Discover parts and return (complete releases for this node, incomplete ones, all parts)."""
    parts = apply_pins(discover_parts())
    here = node_platform()
    releases = assemble_releases(parts, here)
    if SOURCES["version"]:
        releases = [r for r in releases if r["version"] == SOURCES["version"]]
    if want_mode:
        releases = [r for r in releases if r["mode"] == want_mode]
    return [r for r in releases if not r["missing"]], [r for r in releases if r["missing"]], parts


def explain_no_release(incomplete, parts, want_mode):
    where = ", ".join(str(r) for r in search_roots())
    if not parts:
        die(f"no parts found (looked in {where}). Put the bundle or part tars next to install.py, "
            "or pass --bundle PATH (folder or .tar)")
    lines = []
    for rel in incomplete:
        lines.append(f"{release_label(rel)} is missing " + "; ".join(rel["missing"]))
    others = sorted({p["meta"].get("platform", "?") for p in parts if p["kind"] != "installer"} - {node_platform()})
    if others:
        lines.append(f"parts for other platforms were found: {', '.join(others)} (this node is {node_platform()})")
    wanted = f"{want_mode} " if want_mode else ""
    version = f" for {SOURCES['version']}" if SOURCES["version"] else ""
    die(f"no complete {wanted}part set{version} for this node. " + (" ".join(lines) or f"Looked in {where}.")
        + " Run 'install.py parts' to see everything that was found.")


def choose_release(state, prev, purpose="install"):
    """Pick the mode (fixed once installed) and the release to deploy."""
    fixed = state.get("mode")
    complete, incomplete, parts = find_releases(fixed)
    if DOWNLOAD["enabled"] or (not complete and offer_download()):
        pick_mode(fixed, ["container", "native"], prev)
        download_parts(mode(), ask_online_version(state))
        complete, incomplete, parts = find_releases(mode())
        if not complete:
            explain_no_release(incomplete, parts, mode())
    else:
        if not complete:
            explain_no_release(incomplete, parts, fixed)
        pick_mode(fixed, [m for m in ("container", "native") if any(r["mode"] == m for r in complete)], prev)
    return pick_release(complete, state, purpose)


def pick_mode(fixed, available, prev):
    if fixed:
        RUNTIME["mode"] = fixed
        good(f"deployment mode: {fixed} (fixed on this node; uninstall first to switch)")
    else:
        step("Deployment mode")
        if len(available) == 1:
            chosen = available[0]
            say(f"  The parts found support only: {MODE_LABELS[chosen]}")
        else:
            chosen = ask_choice("How should LiteLLM run on this node?", [(m, MODE_LABELS[m]) for m in available],
                                prev.get("mode", "container"))
        if prev.get("mode") and prev["mode"] != chosen:
            note(f"the first node uses {prev['mode']} mode - mixing modes works, but keep all nodes alike if you can")
        RUNTIME["mode"] = chosen


def pick_release(complete, state, purpose):
    choices = [r for r in complete if r["mode"] == mode()]
    if len(choices) > 1:
        default = choices[0]
        if purpose == "upgrade":
            newer = [r for r in choices if r["version"] != state.get("version")]
            default = newer[0] if newer else choices[0]
        labels = [(str(i), release_label(r)) for i, r in enumerate(choices)]
        pick = ask_choice("Several releases were found. Which one?", labels, str(choices.index(default)))
        rel = choices[int(pick)]
    else:
        rel = choices[0]
    good(f"using {release_label(rel)}")
    return materialize(rel)


def _check_tar_sidecar(tar):
    if tar in _TAR_SUMS:
        return
    sidecar = tar.with_name(tar.name + ".sha256")
    if sidecar.is_file():
        expected = sidecar.read_text().split()[0]
        print(f"  checking {tar.name} against {sidecar.name}...", flush=True)
        if sha256_file(tar) != expected:
            die(f"{tar} does not match {sidecar.name} - the copy is damaged")
        good(f"{tar.name} matches {sidecar.name}")
    else:
        note(f"no {sidecar.name} next to {tar.name}; relying on the part's own SHA256SUMS")
    _TAR_SUMS[tar] = True


def verify_part_dir(folder, expect_name=None):
    """Every file listed in the part's SHA256SUMS must match; PART.json must be one of them."""
    sums = folder / "SHA256SUMS"
    if not sums.is_file():
        die(f"{folder}: SHA256SUMS is missing")
    entries = []
    for line in sums.read_text().splitlines():
        if line.strip():
            digest, rel = line.split(None, 1)
            entries.append((digest, rel.strip().lstrip("*")))
    root = folder.resolve()
    if "PART.json" not in [rel for _, rel in entries]:
        die(f"{folder}: PART.json is not covered by SHA256SUMS")
    for digest, rel in entries:
        path = (root / rel).resolve()
        if root not in path.parents:
            die(f"unsafe path in {sums}: {rel}")
        if not path.is_file():
            die(f"{folder.name}: file missing: {rel}")
        if sha256_file(path) != digest:
            die(f"{folder.name}: checksum mismatch: {rel} - the part is damaged or was modified")
    meta = load_json(folder / "PART.json")
    if expect_name and meta.get("name") != expect_name:
        die(f"{folder}: PART.json names {meta.get('name')}, expected {expect_name}")
    return meta, len(entries)


def materialize(rel):
    """Make every part of the release a verified folder (extracting from tars when needed)."""
    step("Verifying the parts")
    rel["dirs"] = {}
    for kind, item in rel["parts"].items():
        if item["dir"] is None:
            _check_tar_sidecar(item["tar"])
            target = STAGING / item["name"]
            if target.exists():
                shutil.rmtree(target)
            print(f"  extracting {item['name']} from {item['tar'].name}...", flush=True)
            safe_extract(item["tar"], target, prefix=item["prefix"], free_check=True)
            _STAGED.append(target)
            item["dir"] = target
        print(f"  checking {item['name']}...", flush=True)
        meta, count = verify_part_dir(item["dir"], item["name"])
        item["meta"] = meta
        rel["dirs"][kind] = item["dir"]
        good(f"{item['name']}: {count} files match SHA256SUMS  ({item['where']})")
    first = rel["parts"][RELEASE_KINDS[rel["mode"]][0]]["meta"]
    good(f"LiteLLM {first['litellm_version']} for {first['platform']}, verified at build time: "
         f"{first.get('signature', '?')}; provenance {first.get('provenance', '?')}")
    if rel["mode"] == "container":
        good(f"image {first['image_id'][:12]}, built {first.get('created', '?')}")
    else:
        nm = native_info(rel)
        good(f"native: Python {nm['python']}, {nm['packages']} pinned wheels, Prisma engines {nm['engine_platform']}")
    return rel


