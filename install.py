def cmd_upgrade(args):
    answers, state = require_installed()
    rel = choose_release(state, {}, purpose="upgrade")
    facts = preflight(rel)
    nm = native_info(rel) if mode() == "native" else None
    current = state["ref"]
    step("Upgrade")
    say(f"  {state.get('version')}  ->  {rel['version']}   ({mode()} mode)")
    target = target_ref(rel)
    if current == target and not ask_yes("This node already runs that version. Re-apply anyway?", False):
        return
    if not ask_yes("Have you read the release notes for every version in between?", False):
        die("read https://docs.litellm.ai/release_notes first")
    ref = prepare_runtime(rel, state, {"storage": state.get("storage_path", "home")}, facts)
    has_ca = installed_ca(answers)
    write_file(SRV / "probe.py", PROBE_SOURCE, 0o644)
    write_config(answers, has_ca)
    if mode() == "native":
        write_file(SRV / "native.env", render_native_env(nm), 0o644, owner=False)
    names = secret_names(answers)
    if not run_probe_any(answers, ref, has_ca, names, nm) and not ask_yes("Some checks failed. Continue?", False):
        die(f"upgrade stopped; this node still runs {state.get('version')}")
    say("  The DBA should have a fresh snapshot of the database before the first node migrates.")
    drained = apply_and_start(answers, state, facts, ref, has_ca, names, nm, changed=True)
    post_check(answers)
    if current != ref:
        state.update({"previous_ref": current, "previous_version": state.get("version"),
                      "previous_image_tag": state.get("image_tag"), "previous_image_id": state.get("image_id"),
                      "previous_parts": state.get("parts")})
    state.update(release_state(rel, ref))
    save_json(STATE_PATH, state)
    step("Done")
    if drained:
        say("  Re-enable this node on the load balancer, then upgrade the next node.")


def cmd_rollback(args):
    answers, state = require_installed()
    previous = state.get("previous_ref")
    if not previous:
        die("no previous version recorded on this node")
    if mode() == "container" and podman("image", "exists", previous, check=False).returncode != 0:
        die(f"{previous} is no longer in local storage")
    if mode() == "native" and not (Path(previous) / ".complete").exists():
        die(f"{previous} is no longer installed")
    step("Rollback")
    say(f"  {state.get('version')}  ->  {state.get('previous_version')}   ({mode()} mode)")
    note("Rolling back does NOT undo database migrations. If the old version cannot run on the new schema, "
         "the DBA must restore the pre-upgrade snapshot (all nodes down first).")
    if not ask_yes("Roll back this node?", False):
        return
    nm = installed_native_info(previous) if mode() == "native" else None
    drained = drain_if_running(answers)
    has_ca = installed_ca(answers)
    if mode() == "native":
        switch_current(Path(previous))
    else:
        install_unit_any(render_unit_any(answers, previous, has_ca, secret_names(answers), nm))
    svc("restart")
    ok = wait_ready(answers)
    if not ok:
        show_diagnostics_any()
    for field in ("ref", "version", "image_tag", "image_id", "parts"):
        state[field], state["previous_" + field] = state.get("previous_" + field), state.get(field)
    save_json(STATE_PATH, state)
    if drained and ok:
        say("  Re-enable this node on the load balancer.")


