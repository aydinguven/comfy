def free_gib(path):
    probe = Path(path)
    while not probe.exists():
        probe = probe.parent
    return shutil.disk_usage(str(probe)).free / 2**30


def image_space_gib(meta):
    """Rough disk need for one image: unpacked layers (~3x compressed) + load temp copy + headroom."""
    return (meta.get("compressed_bytes") or 2**30) / 2**30 * 4 + 1


