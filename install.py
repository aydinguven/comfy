def latest_release():
    proxy = DOWNLOAD["proxy"]
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({"https": proxy} if proxy else None))
    try:
        request = urllib.request.Request("https://api.github.com/repos/BerriAI/litellm/releases/latest",
                                         headers={"Accept": "application/vnd.github+json"})
        with opener.open(request, timeout=15) as resp:
            data = json.load(resp)
        return data.get("tag_name"), data.get("published_at")
    except (OSError, ValueError):
        return None, None


