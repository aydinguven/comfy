def safe_extract(archive, target, prefix="", free_check=False):
    """Extract a tar (only the members under `prefix`, with the prefix removed), refusing absolute
    paths, '..' and links that leave the target."""
    target = target.resolve()
    target.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive) as tar:
        members = []
        for member in tar.getmembers():
            name = member.name[2:] if member.name.startswith("./") else member.name
            if prefix:
                if not name.startswith(prefix) or name == prefix.rstrip("/"):
                    continue
                name = name[len(prefix):]
            if not name:
                continue
            destination = (target / name).resolve()
            if name.startswith("/") or (destination != target and target not in destination.parents):
                die(f"unsafe path in {archive.name}: {member.name}")
            if member.issym() and target not in (destination.parent / member.linkname).resolve().parents:
                die(f"unsafe link in {archive.name}: {member.name} -> {member.linkname}")
            if not (member.isfile() or member.isdir() or member.issym()):
                continue
            member.name = name
            members.append(member)
        if free_check:
            need = sum(m.size for m in members) / 2**30
            if free_gib(target) < need + 0.5:
                die(f"{target} needs {need:.1f} GiB free to extract {archive.name}; free some space, or extract "
                    "the tar yourself elsewhere and pass that folder with --bundle")
        if hasattr(tarfile, "data_filter"):
            tar.extractall(str(target), members=members, filter="data")
        else:
            tar.extractall(str(target), members=members)


