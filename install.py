def apply_and_start(answers, state, facts, ref, has_ca, names, nm, changed, drained_already=False):
    """Migrate, open the firewall, (re)write the unit and start; skips the restart when nothing changed."""
    unit = render_unit_any(answers, ref, has_ca, names, nm)
    path = unit_path()
    unit_changed = not path.exists() or path.read_text() != unit
    if mode() == "native":
        unit_changed |= not NATIVE_CURRENT.is_symlink() or os.readlink(str(NATIVE_CURRENT)) != ref
    drained = drained_already
    if service_active() and not (changed or unit_changed):
        step("Service")
        good("configuration unchanged - the running gateway was left alone")
        apply_firewall(answers, state, facts)
        return drained
    if not drained:
        drained = drain_if_running(answers)
    migrate_any(ref, has_ca, nm)
    apply_firewall(answers, state, facts)
    step("Service")
    if mode() == "native":
        switch_current(Path(ref))
    install_unit_any(unit)
    svc("restart" if service_active() else "start")
    if not wait_ready(answers):
        show_diagnostics_any()
        die("the gateway did not become ready - see the log above")
    return drained


def cmd_install(args):
    rel, state, prev, facts = load_context(args)
    if prev:
        say("  Previous answers are offered as defaults - press Enter to keep them.")
    answers = collect_answers(prev, facts)
    answers["mode"] = mode()
    node = collect_node_settings(answers, state, rel)
    new_secrets = collect_secrets(answers, prev)
    show_summary(answers, node, rel)
    if not ask_yes("Apply this configuration now?", True):
        die("nothing was changed")

    nm = native_info(rel) if mode() == "native" else None
    ref = prepare_runtime(rel, state, node, facts)
    save_json(ANSWERS_PATH, answers)

    step("Configuration")
    has_ca, changed = install_support_files(answers, node)
    changed |= write_config(answers, has_ca)
    if mode() == "native":
        changed |= write_file(SRV / "native.env", render_native_env(nm), 0o644, owner=False)
    for name, value in new_secrets.items():
        store_secret(name, value)
    names = secret_names(answers)
    missing = [n for n in names if n not in existing_secrets()]
    if missing:
        die("secrets missing after storing: " + ", ".join(missing))
    where = "Podman secrets" if mode() == "container" else f"{SECRETS_FILE} (root only)"
    good(f"config in {SRV}, {len(names)} secrets in {where}")

    if not run_probe_any(answers, ref, has_ca, names, nm):
        if not ask_yes("Some checks failed. Continue anyway?", False):
            die("stopped before touching the running gateway - fix the items above and re-run install")

    drained = apply_and_start(answers, state, facts, ref, has_ca, names, nm, changed or bool(new_secrets))
    post_check(answers)
    state.update(release_state(rel, ref))
    state.update({"mode": mode(), "installed_at": datetime.datetime.now().isoformat(timespec="seconds")})
    save_json(STATE_PATH, state)
    print_lb_summary(answers)
    step("Done")
    if drained:
        say("  Re-enable this node on the load balancer.")
    say(f"  Next node: copy {ANSWERS_PATH} (no secrets in it) and the same parts there, then run")
    say("      sudo python3 install.py install --answers install-answers.json"
        + (f" --version {rel['version']}" if SOURCES["version"] else ""))
    say(f"  First login: https://{answers['fqdn']}/ui with the master key; then create your own proxy_admin user.")
    say(f"  Log of this run: {LOG_PATH}")


