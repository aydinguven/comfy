def yaml_scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(value)  # JSON strings/lists/maps are valid YAML flow scalars


def yaml_lines(data, indent=0):
    lines = []
    for index, (key, value) in enumerate(data.items()):
        if indent == 0 and index:
            lines.append("")
        pad = "  " * indent
        if isinstance(value, dict) and value:
            lines.append(f"{pad}{key}:")
            lines.extend(yaml_lines(value, indent + 1))
        else:
            lines.append(f"{pad}{key}: {yaml_scalar(value)}")
    return lines


def render_config(a, has_ca):
    general = {
        "master_key": "os.environ/LITELLM_MASTER_KEY",
        "database_url": "os.environ/DATABASE_URL",
        "store_model_in_db": True,
        "proxy_config_reload_interval_seconds": 30,
        "database_connection_pool_limit": 10,
        "proxy_batch_write_at": 60,
        "disable_error_logs": True,
        "store_prompts_in_spend_logs": False,
        "maximum_spend_logs_retention_period": a["retention"],
        "maximum_spend_logs_retention_interval": "1d",
        "trusted_proxy_ranges": a["lb_cidrs"],
    }
    if a["pg_bouncer_tx"]:
        general["database_disable_prepared_statements"] = True

    client = {}
    if a["redis_username"]:
        client["username"] = a["redis_username"]
    if a["redis_tls"]:
        client["ssl"] = True
        if has_ca:
            client["ssl_ca_certs"] = ca_path()
    if a["redis_auth"]:
        client["password"] = "os.environ/REDIS_PASSWORD"

    cache = {"type": "redis", "mode": "default_off", "namespace": "litellm"}
    router = {"routing_strategy": "simple-shuffle"}
    if a["redis_topology"] == "standalone":
        cache.update({"host": "os.environ/REDIS_HOST", "port": "os.environ/REDIS_PORT"})
        router.update({"redis_host": "os.environ/REDIS_HOST", "redis_port": "os.environ/REDIS_PORT"})
        if a["redis_auth"]:
            router["redis_password"] = "os.environ/REDIS_PASSWORD"
        extra = {k: v for k, v in client.items() if k != "password"}
        if extra:
            router["cache_kwargs"] = extra
    elif a["redis_topology"] == "sentinel":
        cache.update({"service_name": a["redis_service_name"], "sentinel_nodes": a["redis_nodes"]})
        if a.get("redis_sentinel_auth"):
            cache["sentinel_password"] = "os.environ/REDIS_SENTINEL_PASSWORD"
    else:
        cache["redis_startup_nodes"] = [{"host": h, "port": str(p)} for h, p in a["redis_nodes"]]
    cache.update(client)

    settings = {
        "request_timeout": 600,
        "set_verbose": False,
        "json_logs": True,
        "cache": True,
        "enable_redis_auth_cache": True,
        "cache_params": cache,
    }
    header = [
        "# Generated by install.py - re-run the installer to change it. Identical on every node.",
        "# Models are managed in the Admin UI and stored in PostgreSQL. No secrets in this file.",
    ]
    if a["redis_topology"] != "standalone":
        header.append("# Redis " + a["redis_topology"] + ": shared state (rate limits, budgets, locks) uses cache_params;"
                      " router cooldowns stay per worker.")
    body = yaml_lines({"general_settings": general, "litellm_settings": settings, "router_settings": router})
    return "\n".join(header + [""] + body) + "\n"


