def _next_subid(path):
    end = 100000
    for line in Path(path).read_text().splitlines():
        parts = line.split(":")
        if len(parts) == 3 and parts[1].isdigit() and parts[2].isdigit():
            end = max(end, int(parts[1]) + int(parts[2]))
    return ((end + 65535) // 65536) * 65536


