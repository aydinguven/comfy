def builder_python(chosen_mode):
    """Python to run the downloader with: any 3.9+ for container, 3.11+ (tomllib) for native."""
    if chosen_mode == "container" or sys.version_info >= (3, 11):
        return sys.executable
    for name in (f"python{NATIVE_PYTHON}", "python3.14", "python3.13", "python3.12", "python3.11"):
        found = shutil.which(name)
        if found:
            return found
    note(f"downloading the native parts needs Python 3.11+; native mode needs python{NATIVE_PYTHON} anyway")
    dnf_install([f"python{NATIVE_PYTHON}"])
    found = shutil.which(f"python{NATIVE_PYTHON}")
    if not found:
        die(f"python{NATIVE_PYTHON} is still missing")
    return found


